import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import vm from 'node:vm';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'E:/Projects/chad-hamilton-portfolio/node_modules/playwright');
const origin = process.env.GAMING_TEST_ORIGIN || 'http://127.0.0.1:4347';
const read = path => readFile(new URL('../' + path, import.meta.url), 'utf8');
const home = JSON.parse(await read('src/data/media/home.json'));
const before = JSON.parse(execFileSync('git', ['show', 'HEAD:src/data/media/home.json'], { encoding: 'utf8' }));
before.find(item => item.id === 'home-games').href = '/games.html';
assert.deepEqual(home, before, 'HOME changes only the Games destination; all crops/styles/content/portal metadata preserved');
const snapshot = JSON.parse(await read('public/gaming/data/public-snapshot.json'));
const record = snapshot.collections.experiences.find(item => item.gameId === 'game:user:naraka');
const box = vm.createContext({});
vm.runInContext(await read('public/gaming/assets/js/domain/glyph.js'), box);
const expected = box.GOS.glyphEngine.geometry(record.scores, { score: record.score });
const output = join(tmpdir(), 'icy-gaming-layer-validation');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const errors = [], failures = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().startsWith(origin) && response.status() >= 400) failures.push(response.status() + ' ' + response.url()); });
  for (const width of [360, 390, 430, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(origin + '/games.html');
    assert.equal(await page.locator('.score-link strong').textContent(), '9.3');
    assert.equal(await page.locator('.verdict').textContent(), record.verdict);
    assert.equal(await page.locator('.radar-shape').getAttribute('points'), expected.polygon);
    assert.equal(await page.locator('.radar-link svg').getAttribute('data-scale'), '0-10');
    assert.equal(await page.locator('.radar-label').count(), 9);
    assert.equal(await page.locator('.watch-preview').getAttribute('href'), home.find(item => item.id === 'home-games').metadata.canonicalUrl);
    assert.equal(await page.locator('.watch-preview').getAttribute('target'), '_blank');
    assert.equal(await page.locator('.clip').count(), 3);
    assert.deepEqual(await page.locator('.clip').evaluateAll(links => links.map(link => new URL(link.href).searchParams.get('v'))), ['J4Po1W2ROBE', 'ijLxbhyn7hI', 'mdhgL77UL7Y']);
    assert.ok((await page.locator('.watch-preview').boundingBox()).y < 320, 'gameplay appears in the first viewport');
    assert.equal(await page.locator('.more-heading a').getAttribute('href'), 'https://www.youtube.com/@icyclear');
    assert.equal(await page.locator('.system-link').getAttribute('href'), '/gaming/');
    const media = await page.locator('.gameplay').boundingBox();
    const take = await page.locator('.evaluation').boundingBox();
    const system = await page.locator('.system-entry').boundingBox();
    assert.ok(take.y >= media.y + media.height && system.y >= take.y + take.height, 'gameplay → evaluation → system vertically');
    assert.ok((await page.locator('.radar-link').boundingBox()).width >= 280, 'readable mobile radar');
    await page.locator('.dimension-details summary').click();
    for (const point of expected.points) assert.match(await page.locator('.dimension-details dl').textContent(), new RegExp(point.label + point.value + ' / 10'));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no overflow at ' + width);
    await page.screenshot({ path: join(output, `gaming-${width}.png`), fullPage: true });
    await page.locator('.score-link').click();
    await page.waitForFunction(() => window.GOS?.gos?.context().booted);
    assert.equal(new URL(page.url()).search, '?view=history');
    await page.locator(`[data-history-key="${record.id}"]`).click();
    assert.equal(await page.locator('#resultGame').textContent(), record.gameName);
    assert.equal(await page.locator('#resultScore').textContent(), '9.3');
    assert.equal(await page.locator('#resultGlyph .experience-radar__outline').getAttribute('points'), expected.polygon);
    await page.goBack(); await page.goBack();
    assert.equal(new URL(page.url()).pathname, '/games.html');
    console.log(`PASS ${width}: media, exact score/verdict/engine polygon, dimensions, valid History record, Back, vertical sequence, no overflow`);
  }
  const noJS = await browser.newContext({ javaScriptEnabled: false });
  const staticPage = await noJS.newPage(); await staticPage.goto(origin + '/games.html');
  assert.equal(await staticPage.locator('.radar-shape').count(), 1);
  assert.equal(await staticPage.locator('.score-link strong').textContent(), '9.3');
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  console.log('PASS no-JS evaluation/media links; HOME manifest integrity. Screenshots: ' + output);
} finally { await browser.close(); }